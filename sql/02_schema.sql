-- PostgreSQL 15-18: fresh installation, no MySQL compatibility layer.
BEGIN;
CREATE TABLE IF NOT EXISTS records (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK(id BETWEEN 0 AND 4294967295),
 artist varchar(255) NOT NULL, album_title varchar(255) NOT NULL, tracklist_text text,
 release_year integer CHECK(release_year BETWEEN 0 AND 65535),
 album_year integer CHECK(album_year BETWEEN 0 AND 65535),
 catalog_number varchar(255), barcode varchar(255), pressing_plant varchar(255),
 label_name varchar(255), genre_name varchar(255), style_name varchar(255),
 acquired_at timestamp(0) without time zone,
 purchase_price numeric(10,2), purchase_price_usd numeric(10,2), sale_price numeric(10,2),
 storage_status varchar(16) NOT NULL DEFAULT 'in_stock' CHECK(storage_status IN ('in_stock','expected','lent_out')),
 notes text, discogs_release_id bigint CHECK(discogs_release_id BETWEEN 0 AND 4294967295),
 media_condition varchar(64), sleeve_condition varchar(64), discogs_image_url varchar(500),
 created_at timestamp(0) NOT NULL DEFAULT date_trunc('second',statement_timestamp()),
 updated_at timestamp(0) NOT NULL DEFAULT date_trunc('second',statement_timestamp()),
 music_dir varchar(255)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_records_music_dir ON records(music_dir);
CREATE INDEX IF NOT EXISTS idx_artist ON records(artist);
CREATE INDEX IF NOT EXISTS idx_album_title ON records(album_title);
CREATE INDEX IF NOT EXISTS idx_catalog_number ON records(catalog_number);
CREATE INDEX IF NOT EXISTS idx_barcode ON records(barcode);
CREATE INDEX IF NOT EXISTS idx_storage_status ON records(storage_status);
CREATE INDEX IF NOT EXISTS idx_discogs_release_id ON records(discogs_release_id);
CREATE TABLE IF NOT EXISTS users (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK(id BETWEEN 0 AND 4294967295),
 username varchar(64) NOT NULL, password_hash varchar(255) NOT NULL,
 created_at timestamp(0) NOT NULL DEFAULT date_trunc('second',statement_timestamp())
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_users_username ON users(lower(username));
CREATE TABLE IF NOT EXISTS record_photos (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK(id BETWEEN 0 AND 4294967295),
 record_id bigint NOT NULL REFERENCES records(id) ON DELETE CASCADE,
 file_name varchar(255) NOT NULL, file_path varchar(500) NOT NULL,
 is_primary smallint NOT NULL DEFAULT 0 CHECK(is_primary IN (0,1)),
 sort_order bigint NOT NULL DEFAULT 0 CHECK(sort_order BETWEEN 0 AND 4294967295),
 created_at timestamp(0) NOT NULL DEFAULT date_trunc('second',statement_timestamp())
);
CREATE INDEX IF NOT EXISTS idx_record_photos_record_id ON record_photos(record_id);
CREATE TABLE IF NOT EXISTS record_tracks (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK(id BETWEEN 0 AND 4294967295),
 record_id bigint NOT NULL REFERENCES records(id) ON DELETE CASCADE,
 position varchar(32), track_title varchar(255) NOT NULL, duration varchar(32),
 sort_order bigint NOT NULL DEFAULT 0 CHECK(sort_order BETWEEN 0 AND 4294967295),
 audio_path varchar(500), audio_format varchar(8),
 audio_size numeric(20,0) CHECK(audio_size BETWEEN 0 AND 18446744073709551615),
 audio_uploaded_at timestamp(0) without time zone
);
CREATE INDEX IF NOT EXISTS idx_record_tracks_record_id ON record_tracks(record_id);
CREATE OR REPLACE FUNCTION vinyl_records_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW IS DISTINCT FROM OLD AND NEW.updated_at IS NOT DISTINCT FROM OLD.updated_at THEN
  NEW.updated_at := date_trunc('second',statement_timestamp())::timestamp;
 END IF;
 RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS records_updated_at ON records;
CREATE TRIGGER records_updated_at BEFORE UPDATE ON records FOR EACH ROW EXECUTE FUNCTION vinyl_records_updated_at();
COMMIT;
